import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ZhTwChewingDictionaryEntries } from "../packages/aac-core/src/data/zh-tw-chewing.generated.js";

const ScriptDirectory = dirname(fileURLToPath(import.meta.url));
const WorkspaceRoot = resolve(ScriptDirectory, "..");
const EvidencePath = resolve(ScriptDirectory, "data/zhtw-sensitive-candidate-review.json");
const OutputPath = resolve(WorkspaceRoot, "packages/aac-core/src/data/zh-tw-sensitive.generated.js");
const CheckOnly = process.argv.includes("--check");

const evidenceText = await readFile(EvidencePath, "utf8");
const evidence = JSON.parse(evidenceText);
validateEvidence(evidence, new Set(ZhTwChewingDictionaryEntries.map((entry) => entry.label)));

const selected = evidence.candidates
  .filter((candidate) => candidate.disposition === evidence.policy.selectedDisposition)
  .map((candidate) => Object.freeze({
    label: candidate.label,
    policy: candidate.disposition,
    riskSources: Object.freeze([...candidate.riskSources].sort())
  }))
  .sort((left, right) => left.label.localeCompare(right.label, "zh-Hant"));
const evidenceSha256 = createHash("sha256").update(evidenceText).digest("hex");
const output = [
  "// Generated by scripts/generate-zhtw-sensitive-data.mjs.",
  "// Source review: scripts/data/zhtw-sensitive-candidate-review.json",
  "// Do not hand-edit this file or add runtime-only label exceptions.",
  `export const ZhTwSensitiveSuggestionMetadata = Object.freeze(${JSON.stringify({
    evidenceVersion: evidence.version,
    evidenceSha256,
    reviewedCandidateCount: evidence.candidates.length,
    softDemotionCount: selected.length,
    minimumIndependentRiskSources: evidence.policy.minimumIndependentRiskSources
  })});`,
  "export const ZhTwSensitiveSuggestionEntries = Object.freeze([",
  ...selected.map((entry) => `  Object.freeze(${JSON.stringify(entry)}),`),
  "]);",
  ""
].join("\n");

if (CheckOnly) {
  const existing = await readFile(OutputPath, "utf8");
  if (existing !== output) {
    throw new Error("zh-TW sensitive suggestion metadata is stale; run npm run generate:zhtw:sensitive");
  }
  console.log(`Verified ${selected.length} generated soft-demotion labels`);
} else {
  await writeFile(OutputPath, output, "utf8");
  console.log(`Generated ${selected.length} soft-demotion labels at ${OutputPath}`);
}

function validateEvidence(value, dictionaryLabels) {
  if (!value?.version || !value?.policy || !Array.isArray(value.sources) || !Array.isArray(value.candidates)) {
    throw new Error("Invalid zh-TW sensitive suggestion evidence structure");
  }
  const sourceIds = new Set();
  for (const source of value.sources) {
    if (!source.id || !source.kind || !source.revision || !source.url || sourceIds.has(source.id)) {
      throw new Error(`Invalid or duplicate evidence source ${source.id ?? "<missing>"}`);
    }
    sourceIds.add(source.id);
  }
  const labels = new Set();
  for (const candidate of value.candidates) {
    if (!candidate.label || labels.has(candidate.label)) {
      throw new Error(`Invalid or duplicate reviewed label ${candidate.label ?? "<missing>"}`);
    }
    labels.add(candidate.label);
    if (!dictionaryLabels.has(candidate.label)) {
      throw new Error(`Reviewed label ${candidate.label} is absent from the generated zh-TW dictionary`);
    }
    if (!Array.isArray(candidate.riskSources) || !candidate.rationale || !candidate.disposition) {
      throw new Error(`Incomplete review evidence for ${candidate.label}`);
    }
    const independentSources = new Set(candidate.riskSources);
    for (const sourceId of independentSources) {
      if (!sourceIds.has(sourceId)) throw new Error(`Unknown evidence source ${sourceId} for ${candidate.label}`);
    }
    if (
      candidate.disposition === value.policy.selectedDisposition &&
      independentSources.size < value.policy.minimumIndependentRiskSources
    ) {
      throw new Error(`${candidate.label} lacks independent evidence for soft demotion`);
    }
  }
}
