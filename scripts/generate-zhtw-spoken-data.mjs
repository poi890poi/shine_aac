import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ZhTwChewingDictionaryEntries } from "../packages/aac-core/src/data/zh-tw-chewing.generated.js";
import { loadNccuConversationCorpus } from "./lib/nccu-conversation-corpus.mjs";

const ScriptDirectory = dirname(fileURLToPath(import.meta.url));
const WorkspaceRoot = resolve(ScriptDirectory, "..");
const OutputPath = resolve(WorkspaceRoot, "packages/aac-core/src/data/zh-tw-spoken.generated.js");
const corpusDirectory = argumentValue("--corpus-dir") ?? process.env.SHINE_NCCU_CORPUS_DIR;
const corpus = await loadNccuConversationCorpus(corpusDirectory);
const ZhTwFrequencyDictionary = ZhTwChewingDictionaryEntries.map((entry, index) => ({
  ...entry,
  keys: entry.keys ?? [entry.key],
  frequencyRank: entry.sourceRank ?? index + 1,
  frequency: entry.frequency ?? 1 / (index + 1)
}));
const evidence = buildSpokenEvidence(corpus.conversations);

await mkdir(dirname(OutputPath), { recursive: true });
await writeFile(OutputPath, [
  "// Generated by scripts/generate-zhtw-spoken-data.mjs.",
  "// Aggregate counts from the NCCU Corpus of Spoken Taiwan Mandarin, TM001-TM050.",
  "// Source transcripts are not redistributed by this repository.",
  `export const ZhTwSpokenEvidenceMetadata = Object.freeze(${JSON.stringify({
    corpusVersion: corpus.version,
    normalizedSha256: corpus.normalizedSha256,
    conversations: corpus.conversations.length,
    turns: corpus.turnCount,
    hanCharacters: corpus.hanCharacterCount
  })});`,
  "export const ZhTwSpokenEvidenceEntries = Object.freeze([",
  ...evidence.map((entry) => `  Object.freeze(${JSON.stringify(entry)}),`),
  "]);",
  ""
].join("\n"), "utf8");

console.log(`Generated ${evidence.length} spoken-frequency entries at ${OutputPath}`);

function buildSpokenEvidence(conversations) {
  const canonicalGlyphEntries = canonicalGlyphEntryMap();
  const targets = sourceReachableFirstSymbolTargets();
  const labels = new Set(targets.keys());
  const lengths = [...new Set([...labels].map((label) => label.length))];
  const tokenCounts = new Map();
  const conversationCounts = new Map();

  for (const conversation of conversations) {
    const seen = new Set();
    for (const { text } of conversation.turns) {
      for (let offset = 0; offset < text.length; offset += 1) {
        for (const length of lengths) {
          if (offset + length > text.length) continue;
          const label = text.slice(offset, offset + length);
          if (!labels.has(label)) continue;
          tokenCounts.set(label, (tokenCounts.get(label) ?? 0) + 1);
          seen.add(label);
        }
      }
    }
    for (const label of seen) conversationCounts.set(label, (conversationCounts.get(label) ?? 0) + 1);
  }

  return [...tokenCounts].map(([label, tokenCount]) => {
    const baselineSelections = Array.from(label).reduce((sum, character) => {
      const entry = canonicalGlyphEntries.get(character);
      return sum + (entry ? entry.key.length + 1 : 5);
    }, 0);
    const selectionSavings = Math.max(1, baselineSelections - 2);
    return {
      label,
      firstSymbol: targets.get(label),
      tokenCount,
      conversationCount: conversationCounts.get(label) ?? 0,
      selectionSavings,
      utility: tokenCount * selectionSavings
    };
  }).sort((left, right) =>
    right.utility - left.utility ||
    right.conversationCount - left.conversationCount ||
    left.label.localeCompare(right.label, "zh-Hant")
  );
}

function sourceReachableFirstSymbolTargets() {
  const targets = new Map();
  const canonicalEntries = new Map();
  for (const entry of ZhTwFrequencyDictionary) {
    if (!canonicalEntries.has(entry.label)) canonicalEntries.set(entry.label, entry);
  }
  const reachableBySymbol = new Map(
    [...new Set([...canonicalEntries.values()].map((entry) => entry.key.at(0)))]
      .map((symbol) => [
        symbol,
        new Set(sourceFirstSymbolCandidates(symbol).slice(0, 42).map((candidate) => candidate.label))
      ])
  );
  for (const entry of canonicalEntries.values()) {
    const firstSymbol = entry.key.at(0);
    if (reachableBySymbol.get(firstSymbol)?.has(entry.label)) {
      targets.set(entry.label, firstSymbol);
    }
  }
  return targets;
}

function sourceFirstSymbolCandidates(symbol) {
  const seen = new Set();
  const ranked = [];
  for (const entry of ZhTwFrequencyDictionary) {
    const matchingKey = (entry.keys ?? [entry.key])
      .filter((key) => key.startsWith(symbol))
      .sort((left, right) => left.length - right.length)[0];
    const identity = `${entry.label}\u0000${entry.output}`;
    if (!matchingKey || seen.has(identity) || ["是不是", "要不要"].includes(entry.label)) continue;
    seen.add(identity);
    ranked.push({ ...entry, zhuyinKey: matchingKey });
  }
  ranked.sort((left, right) => left.frequencyRank - right.frequencyRank);
  const immediate = ranked.slice(0, 8);
  const remaining = ranked.slice(8);
  return [
    ...immediate,
    ...remaining.filter((candidate) => candidate.zhuyinKey.length === 1),
    ...remaining.filter((candidate) => candidate.zhuyinKey.length !== 1)
  ];
}

function canonicalGlyphEntryMap() {
  const map = new Map();
  for (const entry of ZhTwFrequencyDictionary) {
    if (entry.label.length !== 1) continue;
    const existing = map.get(entry.label);
    if (!existing || entry.frequencyRank < existing.frequencyRank) map.set(entry.label, entry);
  }
  return map;
}

function argumentValue(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}
