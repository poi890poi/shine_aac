import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { inflateRawSync } from "node:zlib";
import https from "node:https";

const __dirname = dirname(fileURLToPath(import.meta.url));
const WorkspaceRoot = resolve(__dirname, "..");
const LocalSourceTextPath = resolve(WorkspaceRoot, ".tmp/shrest18.txt");
const LocalSourceZipPath = resolve(WorkspaceRoot, ".tmp/shrest18.zip");
const OutputPath = resolve(WorkspaceRoot, "packages/aac-core/src/data/zh-tw-moe-glyph-frequency.generated.js");
const SourcePageUrl = "https://language.moe.gov.tw/001/Upload/files/SITE_CONTENT/M0001/PRIMARY/shrest2-18.htm";
const SourceZipUrl = "https://language.moe.gov.tw/001/Upload/files/SITE_CONTENT/M0001/PRIMARY/download/shrest18.zip";
const ExpectedEntryCount = 4343;

const sourceBytes = await readSourceTextBytes();
const sourceText = new TextDecoder("big5").decode(sourceBytes);
const entries = parseFrequencyEntries(sourceText);
validateEntries(entries);

await mkdir(dirname(OutputPath), { recursive: true });
await writeFile(
  OutputPath,
  [
    "// Generated by scripts/generate-zhtw-moe-glyph-frequency-data.mjs.",
    "// Source: Taiwan Ministry of Education, 國小學童常用字詞調查報告書, 表十八.",
    `// ${SourcePageUrl}`,
    "// Do not hand-edit entries or tune individual glyphs here.",
    "export const MoeZhTwGlyphFrequencyMetadata = Object.freeze({",
    `  sourcePageUrl: ${JSON.stringify(SourcePageUrl)},`,
    `  sourceZipUrl: ${JSON.stringify(SourceZipUrl)},`,
    "  commonStandardGlyphCount: 4808,",
    `  rankedCommonGlyphCount: ${entries.length}`,
    "});",
    "",
    "export const MoeZhTwGlyphFrequencyEntries = Object.freeze([",
    ...entries.map((entry) => `  Object.freeze(${JSON.stringify([entry.glyph, entry.frequency, entry.rank])}),`),
    "]);",
    ""
  ].join("\n"),
  "utf8"
);

console.log(`Generated ${entries.length} MOE zh-TW glyph-frequency entries at ${OutputPath}`);

async function readSourceTextBytes() {
  try {
    return await readFile(LocalSourceTextPath);
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }

  let archive;
  try {
    archive = await readFile(LocalSourceZipPath);
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
    archive = await fetchBuffer(SourceZipUrl);
  }
  return extractFirstZipEntry(archive);
}

function parseFrequencyEntries(text) {
  return [...text.matchAll(/│\s*\d+\s*│\s*(\d+)│\s*(\p{Script=Han})\s*│\s*(\d+)\s*│/gu)]
    .map((match) => Object.freeze({
      rank: Number(match[1]),
      glyph: match[2],
      frequency: Number(match[3])
    }));
}

function validateEntries(entries) {
  if (entries.length !== ExpectedEntryCount) {
    throw new Error(`Expected ${ExpectedEntryCount} MOE glyph entries, got ${entries.length}`);
  }
  if (entries[0]?.glyph !== "的" || entries[0]?.rank !== 1 || entries[0]?.frequency !== 48957) {
    throw new Error("Unexpected first MOE glyph-frequency entry");
  }
  if (new Set(entries.map((entry) => entry.glyph)).size !== entries.length) {
    throw new Error("MOE glyph-frequency source contains duplicate glyphs");
  }
  for (let index = 1; index < entries.length; index += 1) {
    if (entries[index].rank <= entries[index - 1].rank) {
      throw new Error(`MOE glyph ranks are not increasing at ${entries[index].glyph}`);
    }
  }
}

function extractFirstZipEntry(archive) {
  if (archive.readUInt32LE(0) !== 0x04034b50) throw new Error("Unsupported MOE ZIP header");
  const flags = archive.readUInt16LE(6);
  const method = archive.readUInt16LE(8);
  const compressedSize = archive.readUInt32LE(18);
  const expectedSize = archive.readUInt32LE(22);
  const nameLength = archive.readUInt16LE(26);
  const extraLength = archive.readUInt16LE(28);
  if ((flags & 0x08) !== 0) throw new Error("MOE ZIP data descriptors are not supported");
  const dataOffset = 30 + nameLength + extraLength;
  const compressed = archive.subarray(dataOffset, dataOffset + compressedSize);
  const result = method === 0 ? compressed : method === 8 ? inflateRawSync(compressed) : null;
  if (!result) throw new Error(`Unsupported MOE ZIP compression method ${method}`);
  if (result.length !== expectedSize) {
    throw new Error(`Expected ${expectedSize} uncompressed MOE bytes, got ${result.length}`);
  }
  return result;
}

function fetchBuffer(url) {
  return new Promise((resolveFetch, rejectFetch) => {
    https.get(url, (response) => {
      if (response.statusCode !== 200) {
        response.resume();
        rejectFetch(new Error(`Failed to fetch ${url}: HTTP ${response.statusCode}`));
        return;
      }
      const chunks = [];
      response.on("data", (chunk) => chunks.push(chunk));
      response.on("end", () => resolveFetch(Buffer.concat(chunks)));
    }).on("error", rejectFetch);
  });
}
