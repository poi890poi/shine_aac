import { gunzipSync } from "node:zlib";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const SOURCE_REVISION = "127336e9f29d69607eab55982324b210279ae8c5";
const SOURCE_URL = `https://android.googlesource.com/platform/packages/inputmethods/LatinIME/+/${SOURCE_REVISION}/dictionaries/en_US_wordlist.combined.gz?format=TEXT`;
// 70 is the highest round cutoff that leaves at least four source-ranked
// completions under every initial a-z letter; 80 leaves only one under x.
const MIN_FREQUENCY = 70;
const OUTPUT_PATH = resolve("packages/aac-core/src/data/en-us-frequency.generated.js");
const SIMPLE_PLUS_S_NON_PLURALS = new Set([
  "besides",
  "corps",
  "does",
  "economics",
  "hers",
  "his",
  "its",
  "mathematics",
  "news",
  "ours",
  "physics",
  "politics",
  "series",
  "sometimes",
  "species",
  "statistics",
  "theirs",
  "towards",
  "yours"
]);

const sourceArgument = process.argv.find((argument) => argument.startsWith("--source="));
const sourcePath = sourceArgument ? resolve(sourceArgument.slice("--source=".length)) : null;
const combined = sourcePath
  ? await readCombinedSource(sourcePath)
  : await downloadCombinedSource();
const sourceMetadata = parseSourceMetadata(combined);
const sourceSha256 = createHash("sha256").update(combined, "utf8").digest("hex");

const parsedEntries = parseEntries(combined);
const supportedEntries = parsedEntries.filter(({ word }) => isSupportedWord(word));
const frequencyQualifiedEntries = supportedEntries.filter(({ frequency }) => frequency >= MIN_FREQUENCY);
const frequencyQualifiedWords = new Set(frequencyQualifiedEntries.map(({ word }) => word));
const simplePluralEntryCount = frequencyQualifiedEntries
  .filter(({ word }) => isSimplePlusSPlural(word, frequencyQualifiedWords)).length;
const entries = frequencyQualifiedEntries
  .filter(({ word }) => !isSimplePlusSPlural(word, frequencyQualifiedWords))
  .sort((left, right) => right.frequency - left.frequency || left.word.localeCompare(right.word));

const generated = `// Generated by scripts/generate-en-us-frequency-data.mjs. Do not edit manually.
// Source: Android Open Source Project LatinIME en_US_wordlist.combined.gz (version ${sourceMetadata.version}).
// Policy: frequency >= ${MIN_FREQUENCY}; ordinary lowercase words plus I, OK, and TV; frequency-0 and simple +s plurals excluded.

export const EnUsFrequencySource = Object.freeze({
  name: "AOSP LatinIME en_US",
  version: ${sourceMetadata.version},
  sourceDate: ${sourceMetadata.date},
  sourceRevision: ${JSON.stringify(SOURCE_REVISION)},
  sourceSha256: ${JSON.stringify(sourceSha256)},
  minimumFrequency: ${MIN_FREQUENCY},
  sourceEntryCount: ${parsedEntries.length},
  supportedEntryCount: ${supportedEntries.length},
  frequencyZeroEntryCount: ${supportedEntries.filter(({ frequency }) => frequency === 0).length},
  simplePluralEntryCount: ${simplePluralEntryCount},
  retainedEntryCount: ${entries.length},
  sourceUrl: ${JSON.stringify(SOURCE_URL)}
});

export const EnUsFrequencyEntries = Object.freeze([
${entries.map(({ word, frequency }) => `  Object.freeze([${JSON.stringify(word)}, ${frequency}]),`).join("\n")}
]);
`;

await writeFile(OUTPUT_PATH, generated, "utf8");
console.log(`Generated ${entries.length} en-US entries at ${OUTPUT_PATH}`);

async function readCombinedSource(path) {
  const bytes = await readFile(path);
  if (path.endsWith(".combined")) return bytes.toString("utf8");
  return gunzipSync(bytes).toString("utf8");
}

async function downloadCombinedSource() {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`Dictionary download failed: HTTP ${response.status}`);
  const encoded = Buffer.from(await response.text(), "base64");
  return gunzipSync(encoded).toString("utf8");
}

function parseEntries(source) {
  const entries = [];
  for (const line of source.split(/\r?\n/u)) {
    const match = line.match(/^ word=([^,]+),f=(\d+),/u);
    if (!match) continue;
    entries.push({ word: match[1], frequency: Number(match[2]) });
  }
  return entries;
}

function parseSourceMetadata(source) {
  const header = source.split(/\r?\n/u, 1)[0];
  const version = Number(header.match(/(?:^|,)version=(\d+)/u)?.[1]);
  const date = Number(header.match(/(?:^|,)date=(\d+)/u)?.[1]);
  if (!Number.isFinite(version) || !Number.isFinite(date)) {
    throw new Error("Could not read source dictionary version/date metadata");
  }
  return { version, date };
}

function isSupportedWord(word) {
  return /^(?:[a-z]+(?:'[a-z]+)*|I|OK|TV)$/u.test(word);
}

function isSimplePlusSPlural(word, eligibleWords) {
  return word === word.toLowerCase() &&
    word.length > 2 &&
    word.endsWith("s") &&
    !word.endsWith("ss") &&
    !SIMPLE_PLUS_S_NON_PLURALS.has(word) &&
    eligibleWords.has(word.slice(0, -1));
}
