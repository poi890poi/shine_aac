import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import https from "node:https";

const __dirname = dirname(fileURLToPath(import.meta.url));
const WorkspaceRoot = resolve(__dirname, "..");
const LocalChewingTsiPath = resolve(WorkspaceRoot, ".tmp/libchewing-data/dict/chewing/tsi.csv");
const OutputPath = resolve(WorkspaceRoot, "packages/aac-core/src/data/zh-tw-chewing.generated.js");
const RemoteChewingTsiUrl = "https://codeberg.org/chewing/libchewing-data/raw/branch/main/dict/chewing/tsi.csv";
const SourceUrl = "https://codeberg.org/chewing/libchewing-data/src/branch/main/dict/chewing/tsi.csv";

const MaxLabelLength = 4;
const MaxKeyLength = 4;
const MaxEntriesPerKey = 45;
const MaxGeneratedEntries = 12000;
const ToneMarks = /[ˊˇˋ˙]/gu;
const ZhuyinSymbols = new Set(Array.from("ㄅㄆㄇㄈㄉㄊㄋㄌㄍㄎㄏㄐㄑㄒㄓㄔㄕㄖㄗㄘㄙㄧㄨㄩㄚㄛㄜㄝㄞㄟㄠㄡㄢㄣㄤㄥㄦ"));

const rawCsv = await readChewingTsiCsv();
const generatedEntries = buildGeneratedEntries(rawCsv);

await mkdir(dirname(OutputPath), { recursive: true });
await writeFile(
  OutputPath,
  [
    "// Generated by scripts/generate-zhtw-chewing-data.mjs.",
    "// Source: New Chewing libchewing-data dict/chewing/tsi.csv",
    `// ${SourceUrl}`,
    "// Do not hand-edit entries or tune individual suggestions here.",
    "export const ZhTwChewingDictionaryEntries = Object.freeze([",
    ...generatedEntries.map((entry) => `  ${JSON.stringify(entry)},`),
    "]);",
    ""
  ].join("\n"),
  "utf8"
);

console.log(`Generated ${generatedEntries.length} zh-TW Chewing entries at ${OutputPath}`);

async function readChewingTsiCsv() {
  try {
    return await readFile(LocalChewingTsiPath, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  return await fetchText(RemoteChewingTsiUrl);
}

function buildGeneratedEntries(raw) {
  const bestByLabelAndKey = new Map();
  let sourceIndex = 0;

  for (const row of parseCsvRows(raw)) {
    if (row.length < 3 || row[0]?.startsWith("#")) continue;
    const label = row[0]?.trim();
    const priority = Number.parseInt(row[1], 10);
    const zhuyin = row.slice(2).join(",").trim();
    sourceIndex += 1;

    if (!label || !Number.isFinite(priority) || priority <= 0) continue;
    if (!/^\p{Script=Han}+$/u.test(label)) continue;
    if (Array.from(label).length > MaxLabelLength) continue;

    const syllables = zhuyin.split(/\s+/u).map(normalizeSyllable).filter(Boolean);
    if (syllables.length === 0) continue;

    const fullKey = syllables.join("");
    const aliasKey = syllables.length > 1 ? syllables.map((syllable) => syllable.at(0)).join("") : "";
    const keys = [...new Set([fullKey, aliasKey].filter(Boolean))];
    for (const key of keys) {
      if (Array.from(key).length > MaxKeyLength) continue;
      if (!isValidZhuyinKey(key)) continue;
      const dedupeKey = `${label}\u0000${key}`;
      const existing = bestByLabelAndKey.get(dedupeKey);
      if (!existing || priority > existing.priority) {
        bestByLabelAndKey.set(dedupeKey, { label, output: label, key, priority, sourceIndex });
      }
    }
  }

  return [...trimPerKey(bestByLabelAndKey.values()).values()]
    .sort(compareEntries)
    .slice(0, MaxGeneratedEntries)
    .map((entry, index) => ({
      label: entry.label,
      output: entry.output,
      key: entry.key,
      frequency: entry.priority,
      sourceRank: index + 1,
      source: "new-chewing"
    }));
}

function trimPerKey(entries) {
  const byKey = new Map();
  for (const entry of entries) {
    if (!byKey.has(entry.key)) byKey.set(entry.key, []);
    byKey.get(entry.key).push(entry);
  }

  const kept = new Map();
  for (const entriesForKey of byKey.values()) {
    for (const entry of entriesForKey.sort(compareEntries).slice(0, MaxEntriesPerKey)) {
      kept.set(`${entry.label}\u0000${entry.key}`, entry);
    }
  }
  return kept;
}

function compareEntries(left, right) {
  return right.priority - left.priority ||
    left.sourceIndex - right.sourceIndex ||
    Array.from(left.label).length - Array.from(right.label).length ||
    left.label.localeCompare(right.label, "zh-Hant");
}

function normalizeSyllable(value) {
  return Array.from(value.replace(ToneMarks, "")).filter((symbol) => ZhuyinSymbols.has(symbol)).join("");
}

function isValidZhuyinKey(value) {
  return Array.from(value).every((symbol) => ZhuyinSymbols.has(symbol));
}

function parseCsvRows(raw) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;

  for (let index = 0; index < raw.length; index += 1) {
    const character = raw[index];
    if (inQuotes) {
      if (character === "\"") {
        if (raw[index + 1] === "\"") {
          field += "\"";
          index += 1;
        } else {
          inQuotes = false;
        }
      } else {
        field += character;
      }
      continue;
    }

    if (character === "\"") {
      inQuotes = true;
    } else if (character === ",") {
      row.push(field);
      field = "";
    } else if (character === "\n") {
      row.push(field.replace(/\r$/u, ""));
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += character;
    }
  }

  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

function fetchText(url) {
  return new Promise((resolveFetch, rejectFetch) => {
    https.get(url, (response) => {
      if (response.statusCode !== 200) {
        response.resume();
        rejectFetch(new Error(`Failed to fetch ${url}: HTTP ${response.statusCode}`));
        return;
      }
      response.setEncoding("utf8");
      let body = "";
      response.on("data", (chunk) => {
        body += chunk;
      });
      response.on("end", () => resolveFetch(body));
    }).on("error", rejectFetch);
  });
}
